def blocks(c, rows, col_w):
    """Measure first, draw second: the picture gets whatever height the text does not need."""
    out = []
    for label, text in rows:
        lines = wrap(c, text, 'Cap', 8.2, col_w)
        out.append((label, lines, 4.2 * mm + len(lines) * 3.5 * mm + 2.4 * mm))
    return out


def split(heights):
    """Cut the blocks into two columns at the point that makes the taller column as short as possible."""
    best, cut = None, 1
    for k in range(1, len(heights)):
        tall = max(sum(heights[:k]), sum(heights[k:]))
        if best is None or tall < best:
            best, cut = tall, k
    return cut, (best or sum(heights))


def flat(fn):
    """One JPEG per frame: a 28 MB book of screenshots is a book nobody opens on a phone."""
    os.makedirs(JPG, exist_ok=True)
    out = os.path.join(JPG, fn.replace('.png', '.jpg'))
    if not os.path.exists(out):
        Image.open(os.path.join(SHOTS, fn)).convert('RGB').save(out, 'JPEG', quality=88, optimize=True)
    return out


def sheet(c, fn, title, sub, rows):
    path = flat(fn)
    c.setFillColor(PAPER); c.rect(0, 0, W, H, fill=1, stroke=0)

    M = 16 * mm
    col_w = (W - 2 * M - 8 * mm) / 2
    bs = blocks(c, rows, col_w)
    cut, cap_h = split([b[2] for b in bs])

    # title 16pt, subtitle 9.2pt, the gaps between them, and a foot margin
    head_h = 9 * mm + 5.4 * mm + 6.4 * mm
    avail = H - M - head_h - cap_h - 13 * mm

    img_w = W - 2 * M
    img_h = img_w * 1000.0 / 1600.0
    if img_h > avail:
        img_h = avail
        img_w = img_h * 1600.0 / 1000.0
    img_x = (W - img_w) / 2
    top = H - M
    c.drawImage(path, img_x, top - img_h, img_w, img_h, mask=None)
    c.setStrokeColor(colors.Color(.80, .80, .78)); c.setLineWidth(.6)
    c.rect(img_x, top - img_h, img_w, img_h, fill=0, stroke=1)

    y = top - img_h - 9 * mm
    c.setFillColor(INK); c.setFont('BodyB', 16); c.drawString(M, y, title)
    y -= 5.4 * mm
    c.setFillColor(RED); c.setFont('Cap', 9.2); c.drawString(M, y, sub)
    y -= 6.4 * mm

    col_x = [M, M + col_w + 8 * mm]
    col_y = [y, y]
    for i, (label, lines, _) in enumerate(bs):
        col = 0 if i < cut else 1
        c.setFillColor(GREY); c.setFont('CapB', 7.6)
        c.drawString(col_x[col], col_y[col], label.upper())
        col_y[col] -= 4.2 * mm
        c.setFillColor(INK); c.setFont('Cap', 8.2)
        for ln in lines:
            c.drawString(col_x[col], col_y[col], ln)
            col_y[col] -= 3.5 * mm
        col_y[col] -= 2.4 * mm
    if min(col_y) < 8 * mm:
        print('!! overflow on', fn, round(min(col_y) / mm, 1), 'mm')
    c.showPage()


